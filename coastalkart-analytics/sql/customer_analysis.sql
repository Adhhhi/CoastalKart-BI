-- QUERY 7: Customer Segment Performance & Average Order Value
-- Business Question: How do Retail, Prime, Kirana, and Corporate customer segments compare in revenue and order frequency?
-- Result Explanation: Joins customers to completed transactions to compute active buyers, orders per customer, and total segment revenue.
-- Business Recommendation: Expand Bulk / Kirana Partner credit-linked UPI incentives in Udupi and Kasaragod where wholesale repeat frequency is high.
SELECT
    c.customer_segment,
    COUNT(DISTINCT c.customer_id) AS active_customers,
    COUNT(DISTINCT s.order_id) AS total_orders,
    ROUND(COUNT(DISTINCT s.order_id) * 1.0 / COUNT(DISTINCT c.customer_id), 2) AS avg_orders_per_customer,
    ROUND(SUM(s.revenue), 2) AS total_revenue,
    ROUND(SUM(s.revenue) / COUNT(DISTINCT c.customer_id), 2) AS revenue_per_customer
FROM customers c
JOIN sales_transactions s ON c.customer_id = s.customer_id
WHERE s.order_status = 'Completed'
GROUP BY c.customer_segment
ORDER BY total_revenue DESC;

-- QUERY 8: Repeat Buyer vs One-Time Buyer Revenue Share
-- Business Question: What proportion of CoastalKart revenue is generated by repeat customers versus one-time shoppers?
-- Result Explanation: Uses a customer-level CTE to classify buyers with >=2 distinct orders as Repeat Buyers vs One-Time Buyers.
-- Business Recommendation: Implement a 2nd-order welcome coupon triggered 7 days after first delivery to convert one-time shoppers into repeat buyers.
WITH customer_orders AS (
    SELECT
        customer_id,
        COUNT(DISTINCT order_id) AS order_count,
        SUM(revenue) AS total_spend
    FROM sales_transactions
    WHERE order_status = 'Completed'
    GROUP BY customer_id
)
SELECT
    CASE WHEN order_count >= 2 THEN 'Repeat Buyer (2+ Orders)' ELSE 'One-Time Buyer (1 Order)' END AS buyer_type,
    COUNT(*) AS customer_count,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS customer_share_pct,
    ROUND(SUM(total_spend), 2) AS total_revenue,
    ROUND(SUM(total_spend) * 100.0 / SUM(SUM(total_spend)) OVER (), 2) AS revenue_share_pct
FROM customer_orders
GROUP BY buyer_type
ORDER BY total_revenue DESC;

-- QUERY 9: RFM Scoring & Customer Cohort Classification (NTILE / Quintiles)
-- Business Question: How are customers distributed across RFM value segments (Champions, Loyal, At Risk, Hibernating)?
-- Result Explanation: Computes Recency (days since last order), Frequency, and Monetary spend, scores 1-5 using NTILE(5), and assigns RFM segments.
-- Business Recommendation: Prioritize immediate retention outreach to 'At Risk' buyers with high historical spend before they churn permanently.
WITH customer_rfm AS (
    SELECT
        c.customer_id,
        CAST(JULIANDAY((SELECT MAX(order_date_iso) FROM sales_transactions)) - JULIANDAY(MAX(s.order_date_iso)) AS INTEGER) AS recency_days,
        COUNT(DISTINCT s.order_id) AS frequency,
        ROUND(SUM(s.revenue), 2) AS monetary
    FROM customers c
    JOIN sales_transactions s ON c.customer_id = s.customer_id
    WHERE s.order_status = 'Completed'
    GROUP BY c.customer_id
),
rfm_scores AS (
    SELECT
        *,
        NTILE(5) OVER (ORDER BY recency_days DESC) AS r_score,
        NTILE(5) OVER (ORDER BY frequency ASC) AS f_score,
        NTILE(5) OVER (ORDER BY monetary ASC) AS m_score
    FROM customer_rfm
),
rfm_labeled AS (
    SELECT
        *,
        CASE
            WHEN r_score >= 4 AND f_score >= 4 AND m_score >= 4 THEN 'Champions'
            WHEN f_score >= 3 AND m_score >= 3 AND r_score >= 3 THEN 'Loyal Customers'
            WHEN r_score >= 4 AND f_score <= 2 THEN 'New / Promising'
            WHEN r_score <= 2 AND f_score >= 3 THEN 'At Risk'
            WHEN r_score <= 2 AND f_score <= 2 THEN 'Hibernating'
            ELSE 'Potential Loyalists'
        END AS rfm_segment
    FROM rfm_scores
)
SELECT
    rfm_segment,
    COUNT(*) AS customer_count,
    ROUND(AVG(recency_days), 1) AS avg_recency_days,
    ROUND(AVG(frequency), 2) AS avg_frequency,
    ROUND(AVG(monetary), 2) AS avg_clv_inr,
    ROUND(SUM(monetary), 2) AS segment_revenue
FROM rfm_labeled
GROUP BY rfm_segment
ORDER BY segment_revenue DESC;

-- QUERY 10: Top 15 High-Value Customers & Preferred Payment Channel
-- Business Question: Who are our highest-spending customers and which cities/segments do they belong to?
-- Result Explanation: Ranks individual customers by cumulative completed spend and surfaces their order frequency and city.
-- Business Recommendation: Enroll top 50 non-Prime high-LTV customers into a complimentary 3-month CoastalKart Prime trial.
SELECT
    c.customer_id,
    c.customer_name,
    c.city,
    c.customer_segment,
    COUNT(DISTINCT s.order_id) AS total_orders,
    ROUND(SUM(s.revenue), 2) AS lifetime_spend,
    MAX(s.order_date) AS last_order_date,
    RANK() OVER (ORDER BY SUM(s.revenue) DESC) AS spend_rank
FROM customers c
JOIN sales_transactions s ON c.customer_id = s.customer_id
WHERE s.order_status = 'Completed'
GROUP BY c.customer_id, c.customer_name, c.city, c.customer_segment
ORDER BY lifetime_spend DESC
LIMIT 15;

-- QUERY 11: City-Wise Customer Penetration & Average Spend
-- Business Question: How does customer spend and repeat intensity vary across CoastalKart's 6 operational cities?
-- Result Explanation: Compares unique active buyers, total revenue, and revenue per buyer across Mangaluru, Bengaluru, Udupi, Manipal, Mysuru, and Kasaragod.
-- Business Recommendation: Manipal shows concentrated student demand; introduce semester-start electronics & dorm-essential bundles.
SELECT
    c.city,
    c.state,
    COUNT(DISTINCT c.customer_id) AS active_buyers,
    COUNT(DISTINCT s.order_id) AS total_orders,
    ROUND(SUM(s.revenue), 2) AS total_revenue,
    ROUND(SUM(s.revenue) / COUNT(DISTINCT c.customer_id), 2) AS avg_spend_per_buyer
FROM customers c
JOIN sales_transactions s ON c.customer_id = s.customer_id
WHERE s.order_status = 'Completed'
GROUP BY c.city, c.state
ORDER BY total_revenue DESC;

-- QUERY 12: Payment Method Adoption & Cancellation Risk
-- Business Question: Which payment methods dominate transactions and which carry the highest cancellation/return rates?
-- Result Explanation: Aggregates total orders, completed revenue, and non-completed rate grouped by payment method.
-- Business Recommendation: Add OTP verification or ₹25 prepaid UPI discount on Cash on Delivery orders to curb COD cancellations.
SELECT
    payment_method,
    COUNT(DISTINCT order_id) AS total_orders,
    ROUND(SUM(CASE WHEN order_status = 'Completed' THEN revenue ELSE 0 END), 2) AS completed_revenue,
    ROUND(SUM(CASE WHEN order_status IN ('Cancelled', 'Returned') THEN 1.0 ELSE 0.0 END) * 100.0 / COUNT(*), 2) AS cancellation_return_pct
FROM sales_transactions
GROUP BY payment_method
ORDER BY total_orders DESC;
